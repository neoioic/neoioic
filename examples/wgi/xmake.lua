set_project("oioic-wgi")
set_languages("c11")
set_targetdir(path.join(os.scriptdir(), "build/$(plat)/$(arch)/$(mode)"))
set_objectdir(path.join(os.scriptdir(), "build/.objs/$(target)/$(plat)/$(arch)/$(mode)"))
add_rules("mode.debug", "mode.release")
includes("../../src")
target("wgi")
    on_load(function (target)
        assert(target:is_plat("mingw", "windows"), "WGI requires Windows APIs; configure with -p mingw")
    end)
    set_kind("binary")
    add_deps("oioic")
    add_files("*.c", "so/**.c", "se/**.c")
    add_files("wgidemo.rc")
    add_includedirs(".")
    add_defines("UNICODE", "_UNICODE")
    add_syslinks("user32", "gdi32", "ole32", "oleaut32", "uuid")
    add_ldflags("-mwindows")
    set_warnings("all")
    after_build(function (target)
        os.cp(path.join(target:scriptdir(), "skins"), target:targetdir())
    end)
